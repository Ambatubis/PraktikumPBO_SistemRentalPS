    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        int harga;

        try {

            harga = Integer.parseInt(
                    txtHarga.getText()
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this, "Harga harus berupa angka");

            return;
        }

        Playstation ps = new Playstation();

        ps.setNamaPs(txtNamaPS.getText());
        ps.setTipePs(cbTipe.getSelectedItem().toString());
        ps.setStatusPs(cbStatus.getSelectedItem().toString());
        ps.setHargaPerJam(harga);

        boolean sukses = controller.tambahData(ps);

        if (sukses) {

            JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan");

            tampilTabel();
            resetForm();

        } else {

            JOptionPane.showMessageDialog(this, "Data gagal ditambahkan");

        }
    }//GEN-LAST:event_btnTambahActionPerformed


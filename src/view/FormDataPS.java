    private void tblPSMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPSMouseClicked
        int baris = tblPS.getSelectedRow();

        idPsTerpilih = Integer.parseInt(
                tblPS.getValueAt(baris, 0).toString()
        );

        txtNamaPS.setText(
                tblPS.getValueAt(baris, 1).toString()
        );

        cbTipe.setSelectedItem(
                tblPS.getValueAt(baris, 2).toString()
        );

        cbStatus.setSelectedItem(
                tblPS.getValueAt(baris, 3).toString()
        );

        txtHarga.setText(
                tblPS.getValueAt(baris, 4).toString()
        );
    }//GEN-LAST:event_tblPSMouseClicked

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed

        if(idPsTerpilih == 0){

            JOptionPane.showMessageDialog(
                    this,
                    "Pilih data terlebih dahulu"
            );

            return;
        }
        
        int harga;
        
        try {

            harga = Integer.parseInt(
                    txtHarga.getText()
            );

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Harga harus berupa angka"
            );

            return;
        }

        Playstation ps = new Playstation();

        ps.setIdPs(idPsTerpilih);

        ps.setNamaPs(txtNamaPS.getText());

        ps.setTipePs(cbTipe.getSelectedItem().toString());

        ps.setStatusPs(cbStatus.getSelectedItem().toString());

        ps.setHargaPerJam(
                Integer.parseInt(txtHarga.getText())
        );
        
        boolean sukses = controller.updateData(ps);

        if(sukses){

            JOptionPane.showMessageDialog(this,"Data berhasil diupdate");

            tampilTabel();

            resetForm();

        }else{

            JOptionPane.showMessageDialog(this,"Data gagal diupdate");

        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if(idPsTerpilih == 0){

            JOptionPane.showMessageDialog(this,"Pilih data terlebih dahulu");

            return;
        }

        int jawab =
                JOptionPane.showConfirmDialog(
                        this,
                        "Yakin hapus data?",
                        "Konfirmasi",
                        JOptionPane.YES_NO_OPTION
                );

        if(jawab == JOptionPane.YES_OPTION){

            boolean sukses = controller.hapusData(idPsTerpilih);

            if(sukses){

                JOptionPane.showMessageDialog(this,"Data berhasil dihapus");

                tampilTabel();

                resetForm();

            }else{

                JOptionPane.showMessageDialog(this,"Data gagal dihapus");

            }

        }
    }//GEN-LAST:event_btnHapusActionPerformed


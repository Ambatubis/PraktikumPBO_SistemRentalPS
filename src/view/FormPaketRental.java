    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if(idPaketTerpilih == 0){

            JOptionPane.showMessageDialog(this,"Pilih data terlebih dahulu");

            return;

        }

        int durasi;
        int harga;

        try{

            durasi = Integer.parseInt(txtDurasi.getText());

            harga = Integer.parseInt(txtHarga.getText());

        }catch(NumberFormatException e){

            JOptionPane.showMessageDialog(this,"Durasi dan Harga harus angka");

            return;

        }

        PaketRental paket = new PaketRental();

        paket.setIdPaket(idPaketTerpilih);

        paket.setNamaPaket(txtNamaPaket.getText());

        paket.setDurasiJam(durasi);

        paket.setHargaPaket(harga);

        boolean sukses = controller.updateData(paket);

        if(sukses){

            JOptionPane.showMessageDialog(this, "Data berhasil diupdate");

            tampilTabel();

            resetForm();

        }else{

            JOptionPane.showMessageDialog(this,"Data gagal diupdate");

        }
    }//GEN-LAST:event_btnEditActionPerformed


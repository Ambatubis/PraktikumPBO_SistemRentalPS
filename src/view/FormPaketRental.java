    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if(idPaketTerpilih == 0){

            JOptionPane.showMessageDialog(this,"Pilih data terlebih dahulu");

            return;

        }

        int jawab =
                JOptionPane.showConfirmDialog(
                        this,
                        "Yakin ingin menghapus data?",
                        "Konfirmasi",
                        JOptionPane.YES_NO_OPTION
                );

        if(jawab == JOptionPane.YES_OPTION){

            boolean sukses = controller.hapusData(idPaketTerpilih);

            if(sukses){

                JOptionPane.showMessageDialog(this,"Data berhasil dihapus");

                tampilTabel();

                resetForm();

            }else{

                JOptionPane.showMessageDialog(this,"Data gagal dihapus");

            }

        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void tblPaketRentalMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaketRentalMouseClicked
        int baris = tblPaketRental.getSelectedRow();

        idPaketTerpilih = Integer.parseInt(
                tblPaketRental.getValueAt(baris, 0).toString()
        );

        txtNamaPaket.setText(
                tblPaketRental.getValueAt(baris, 1).toString()
        );

        txtDurasi.setText(
                tblPaketRental.getValueAt(baris, 2).toString()
        );

        txtHarga.setText(
                tblPaketRental.getValueAt(baris, 3).toString()
        );
    }//GEN-LAST:event_tblPaketRentalMouseClicked


    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        if(txtNamaPaket.getText().trim().isEmpty()){

            JOptionPane.showMessageDialog(this, "Nama Paket tidak boleh kosong");

            return;
        }

        int durasi;
        int harga;

        try{

            durasi = Integer.parseInt(txtDurasi.getText());

            harga = Integer.parseInt(txtHarga.getText());

        }catch(NumberFormatException e){

            JOptionPane.showMessageDialog(this, "Durasi dan Harga harus angka");

            return;

        }

        PaketRental paket = new PaketRental();

        paket.setNamaPaket(txtNamaPaket.getText());

        paket.setDurasiJam(durasi);

        paket.setHargaPaket(harga);

        boolean sukses = controller.tambahData(paket);

        if(sukses){

            JOptionPane.showMessageDialog(this, "Data berhasil ditambahkan");

            tampilTabel();

            resetForm();

        }else{

            JOptionPane.showMessageDialog(this, "Data gagal ditambahkan");

        }
    }//GEN-LAST:event_btnTambahActionPerformed

